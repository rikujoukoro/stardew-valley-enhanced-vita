#!/usr/bin/env bash
# Generates the struct offsets header the cross AOT compiler needs (configure --with-cross-offsets),
# from the Vita runtime's own build: run inside WSL as root after `build-mono-vita.sh make`.
#
#   gen-cross-offsets.sh [output]     default: /root/vita/mono-vita/arm-vita-eabi-offsets.h
#
# AOT code reads runtime structures (MonoObject, MonoVTable, MonoLMF, ...) at fixed offsets, so the
# cross compiler must use the Vita runtime's layout, not its own x86_64 one. Mono normally gets them
# from tools/offsets-tool (libclang, not in the release tarball) or from a runtime started with
# DUMP_CROSS_OFFSETS on the target. Here they come from the Vita compiler itself, as Linux generates
# asm-offsets.h: object-offsets.h is compiled with the runtime's exact flags and config.h, each entry
# becomes an asm marker carrying its value as an immediate, and the markers are read back from the
# generated assembly. Nothing runs on the device.
set -euo pipefail

export VITASDK=/usr/local/vitasdk
export PATH="$VITASDK/bin:$PATH"
SRC=/root/vita/src/mono-vita-6.14.1
BUILD=/root/vita/build-mono-vita
OUT="${1:-/root/vita/mono-vita/arm-vita-eabi-offsets.h}"
WORK="$BUILD/cross-offsets"

rm -rf "$WORK"
mkdir -p "$WORK"

# Compiler flags of a runtime library, as its Makefile has them (they hold relative -I paths, so
# compiling happens in that library's build directory).
flags() {
	make -s -C "$BUILD/mono/$1" --eval="vita-print-flags: ; @echo \$(DEFS) \$(DEFAULT_INCLUDES) \$(INCLUDES) \$(AM_CPPFLAGS) \$(CPPFLAGS) \$($2_CPPFLAGS) \$($2_CFLAGS) \$(AM_CFLAGS) \$(CFLAGS)" vita-print-flags | tail -n 1
}

# Asm markers: "@@ DECL_...(name,value)". %c prints an immediate without ARM's '#'.
cat > "$WORK/markers.h" <<'EOF'
#undef DECL_OFFSET
#undef DECL_OFFSET2
#undef DECL_ALIGN
#undef DECL_ALIGN2
#undef DECL_SIZE
#undef DECL_SIZE2
#define VITA_MARK(text, value) __asm__ volatile ("\n@@ " text ",%c0)" :: "i" ((int) (value)))
#define DECL_OFFSET(struct,field) VITA_MARK ("DECL_OFFSET2(" #struct "," #field, G_STRUCT_OFFSET (struct, field));
#define DECL_SIZE(type) VITA_MARK ("DECL_SIZE2(" #type, sizeof (type));
#define DECL_OFFSET2(struct,field,offset) this_should_not_happen
#define DECL_ALIGN2(type,size) this_should_not_happen
#define DECL_SIZE2(type,size) this_should_not_happen
EOF

# Metadata structures (and the basic type sizes and alignments), with the headers
# metadata-cross-helpers.c uses: the file itself is included for them.
cat > "$WORK/metadata-offsets.c" <<'EOF'
#include "metadata-cross-helpers.c"
#include <stddef.h>
void vita_metadata_offsets (void);
void vita_metadata_offsets (void)
{
#define VITA_ALIGN(type) { typedef struct { char c; type x; } vita_align_ ## type; VITA_MARK ("DECL_ALIGN2(" #type, offsetof (vita_align_ ## type, x)); }
#include "markers.h"
	VITA_ALIGN (gint8)
	VITA_ALIGN (gint16)
	VITA_ALIGN (gint32)
	VITA_ALIGN (gint64)
	VITA_ALIGN (float)
	VITA_ALIGN (double)
	VITA_ALIGN (gpointer)
#undef DISABLE_METADATA_OFFSETS
#define DISABLE_JIT_OFFSETS
#include <mono/metadata/object-offsets.h>
}
EOF

# JIT structures, with mini-cross-helpers.c's headers.
cat > "$WORK/jit-offsets.c" <<'EOF'
#include "mini-cross-helpers.c"
void vita_jit_offsets (void);
void vita_jit_offsets (void)
{
#include "markers.h"
#undef DISABLE_JIT_OFFSETS
#define DISABLE_METADATA_OFFSETS
#include <mono/metadata/object-offsets.h>
}
EOF

META_FLAGS="$(flags metadata libmonoruntimesgen_la)"
MINI_FLAGS="$(flags mini libmini_la)"
(cd "$BUILD/mono/metadata" && arm-vita-eabi-gcc $META_FLAGS -I"$WORK" -w -S "$WORK/metadata-offsets.c" -o "$WORK/metadata-offsets.s")
(cd "$BUILD/mono/mini" && arm-vita-eabi-gcc $MINI_FLAGS -I"$WORK" -w -S "$WORK/jit-offsets.c" -o "$WORK/jit-offsets.s")

markers() {
	sed -n 's/^[[:space:]]*@@ \(DECL_[A-Z0-9]*(.*)\)[[:space:]]*$/\1/p' "$1"
}
markers "$WORK/metadata-offsets.s" > "$WORK/metadata.txt"
# The basic type sizes are emitted by both passes; the header keeps them in the metadata part only
# (abi-details.h declares one enum entry per name).
markers "$WORK/jit-offsets.s" | grep -v -E '^DECL_SIZE2\((gint8|gint16|gint32|gint64|float|double|gpointer),' > "$WORK/jit.txt"
for part in metadata jit; do
	[ -s "$WORK/$part.txt" ] || { echo "no $part offsets found"; exit 1; }
	if grep -q 'this_should_not_happen' "$WORK/$part.txt"; then echo "unexpected macro in $part offsets"; exit 1; fi
done

# Same layout as offsets-tool's output: the guards make it apply to an SGen cross compiler for ARM
# with TARGET_VITA defined (configure.ac's arm*-vita*-eabi* cross target defines it).
{
	echo "/* Generated by Tools/Vita/mono-vita/gen-cross-offsets.sh from the Vita runtime build ($(date -u +%Y-%m-%d)). */"
	echo "#ifndef USED_CROSS_COMPILER_OFFSETS"
	echo "#ifdef TARGET_ARM"
	echo "#ifdef TARGET_VITA"
	echo "#ifndef HAVE_BOEHM_GC"
	echo "#define HAS_CROSS_COMPILER_OFFSETS"
	echo "#if defined (USE_CROSS_COMPILE_OFFSETS) || defined (MONO_CROSS_COMPILE)"
	echo "#if !defined (DISABLE_METADATA_OFFSETS)"
	echo "#define USED_CROSS_COMPILER_OFFSETS"
	cat "$WORK/metadata.txt"
	echo "#endif //disable metadata check"
	echo "#ifndef DISABLE_JIT_OFFSETS"
	echo "#define USED_CROSS_COMPILER_OFFSETS"
	cat "$WORK/jit.txt"
	echo "#endif //disable jit check"
	echo "#endif //cross compiler checks"
	echo "#endif //gc check"
	echo "#endif //os check"
	echo "#endif //arch check"
	echo "#endif //USED_CROSS_COMPILER_OFFSETS check"
} > "$OUT"
echo "$OUT: $(wc -l < "$WORK/metadata.txt") metadata and $(wc -l < "$WORK/jit.txt") JIT entries"
