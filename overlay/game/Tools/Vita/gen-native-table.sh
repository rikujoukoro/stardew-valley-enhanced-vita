#!/usr/bin/env bash
# gen-native-table.sh <table-name> <out.c> <symbol-regex> <overrides-file|-> <archive>...
#
# Writes a C file defining `const VitaNativeSymbol vita_<table-name>_symbols[]`: every function the
# archives export whose name matches <symbol-regex>, for vita_native_register_library() to serve to
# [DllImport]. An overrides file lists "<exported name> <replacement function>" pairs; those names
# point at the replacement instead (for Vita-specific behaviour behind an unchanged binding).
set -euo pipefail

name="$1"
out="$2"
regex="$3"
overrides="$4"
shift 4

symbols="$(mktemp)"
arm-vita-eabi-nm -g --defined-only "$@" | awk '$2 == "T" || $2 == "W" { print $3 }' | grep -E "$regex" | sort -u > "$symbols"

declare -A replace=()
if [ "$overrides" != "-" ]; then
	while read -r symbol replacement; do
		[ -z "$symbol" ] || [ "${symbol:0:1}" = "#" ] && continue
		replace["$symbol"]="$replacement"
	done < "$overrides"
fi

{
	echo "/* Generated by gen-native-table.sh: $(wc -l < "$symbols") functions for \"$name\". */"
	echo '#include "vita_native.h"'
	while read -r symbol; do
		echo "extern void ${replace[$symbol]:-$symbol}(void);"
	done < "$symbols"
	echo "const VitaNativeSymbol vita_${name}_symbols[] = {"
	while read -r symbol; do
		echo "	{ \"$symbol\", (void *)&${replace[$symbol]:-$symbol} },"
	done < "$symbols"
	echo '	{ 0, 0 }'
	echo '};'
} > "$out"
echo "$name: $(wc -l < "$symbols") functions -> $out"
rm -f "$symbols"
