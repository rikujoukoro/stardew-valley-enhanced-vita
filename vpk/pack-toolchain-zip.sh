#!/usr/bin/env bash
# Maintainer tool, inside the WSL that builds the port: packs what the builder needs to make stardew.vpk on a
# player's Windows or Linux into one zip per system (no game files in it). VitaSDK itself is not in it: the builder
# downloads the official release for the system (tools/sources.json).
#
#   bash vpk/pack-toolchain-zip.sh windows|linux <output.zip>
#
# Contents (paths in the zip); only mono/bin differs between the two:
#   mono/bin            the AOT cross compiler for the system (build-mono-crosswin.sh, build-mono-crosslinux.sh)
#   mono/lib/mono/4.5   the class libraries the game loads (also copied into the VPK), mono/etc its config
#   lib                 the static libraries the eboot links (SDL3, FNA3D, MojoShader, FAudio, vitaGL, the Vita
#                       Mono runtime and its helpers)
#   launcher            the launcher's own objects (stardew/main.c, the native tables, the FNA glue and the AOT
#                       module table): everything of the eboot that doesn't depend on the game, compiled here with
#                       stardew/CMakeLists.txt's flags
#   game.aotprofile     assets/stardew-1.aotprofile filtered as aot-stardew.sh filters it (the profile and the
#                       filter are ours, so the result is the same for every player)
#   licenses            as in pack-toolchain.sh, including vitaGL's complete source (LGPL-3.0: the player links
#                       the eboot, so a modified vitaGL can be relinked the same way)
set -euo pipefail

HOST="${1:?usage: pack-toolchain-zip.sh windows|linux <output.zip>}"
OUT="$(realpath "${2:?usage: pack-toolchain-zip.sh windows|linux <output.zip>}")"
HERE="$(dirname "$(realpath "$0")")"
REPO="$HERE/.."
TOOLS="$REPO/overlay/game/Tools/Vita"
V=/root/vita
export VITASDK=/usr/local/vitasdk
export PATH="$VITASDK/bin:$PATH"
STAGE=/root/vita/toolchain-$HOST
CC=(arm-vita-eabi-gcc -I"$V/prefix/include" -I"$TOOLS/fna-vita" -I"$V/mono-vita/include/mono-2.0" -I"$V/mono-vita/include/vita" -Wl,-q -O3 -DNDEBUG -fno-short-enums)

case "$HOST" in
	windows) COMPILER=("$V/mono-crosswin/bin/mono-sgen.exe" "$V/mono-crosswin/bin/libmonosgen-2.0.dll"); SCRIPT=build-mono-crosswin.sh ;;
	linux) COMPILER=("$V/mono-crosslinux/bin/mono-sgen"); SCRIPT=build-mono-crosslinux.sh ;;
	*) echo "unknown system $HOST"; exit 1 ;;
esac
for f in "${COMPILER[@]}"; do [ -f "$f" ] || { echo "no $f (run $SCRIPT)"; exit 1; }; done
rm -rf "$STAGE"
mkdir -p "$STAGE/mono/bin" "$STAGE/mono/lib/mono/4.5" "$STAGE/mono/etc/mono/4.5" "$STAGE/lib" "$STAGE/launcher" "$STAGE/tables"

cp "${COMPILER[@]}" "$STAGE/mono/bin/"
for dll in mscorlib System System.Core System.Xml System.Numerics System.Configuration System.Security Mono.Security; do
	cp -L "$V/mono-host/lib/mono/4.5/$dll.dll" "$STAGE/mono/lib/mono/4.5/"
done
cp "$V/mono-host/etc/mono/config" "$STAGE/mono/etc/mono/config"
cp "$V/mono-host/etc/mono/4.5/machine.config" "$STAGE/mono/etc/mono/4.5/machine.config"

for l in FNA3D mojoshader FAudio SDL3 vitaGL; do cp "$V/prefix/lib/lib$l.a" "$STAGE/lib/"; done
for l in vitanative mono-profiler-aot vita-sampler monosgen-2.0 vitashim; do cp "$V/mono-vita/lib/lib$l.a" "$STAGE/lib/"; done

# The native tables, as build-stardew.sh makes them.
T="$STAGE/tables"
bash "$TOOLS/gen-native-table.sh" sdl3 "$T/vita_sdl3_table.c" '^SDL_' "$TOOLS/fna-vita/sdl3.overrides" "$V/prefix/lib/libSDL3.a"
bash "$TOOLS/gen-native-table.sh" fna3d "$T/vita_fna3d_table.c" '^(FNA3D_|MOJOSHADER_)' - \
	"$V/prefix/lib/libFNA3D.a" "$V/prefix/lib/libmojoshader.a"
bash "$TOOLS/gen-native-table.sh" faudio "$T/vita_faudio_table.c" '^(F3DAudio|FACT|FAPO|FAudio|CreateFAPO|XNA_|qoa_|ReverbConvert)' - \
	"$V/prefix/lib/libFAudio.a"
# The AOT module table for the assemblies the builder compiles (aot-stardew.sh's default list, in its order).
{
	echo "/* Generated by pack-toolchain-zip.sh: the AOT images linked into the eboot (see main.c). */"
	echo "#include <stddef.h>"
	for n in mscorlib System System_Core System_Xml StardewValley_GameData BmFont Stardew_Valley; do echo "extern void *mono_aot_module_${n}_info;"; done
	echo "void **const vita_aot_modules[] = {"
	for n in mscorlib System System_Core System_Xml StardewValley_GameData BmFont Stardew_Valley; do echo "	&mono_aot_module_${n}_info,"; done
	echo "	NULL"
	echo "};"
} > "$T/vita_aot_modules.c"
for src in "$TOOLS/stardew/main.c" "$T/vita_sdl3_table.c" "$T/vita_fna3d_table.c" "$T/vita_faudio_table.c" \
	"$TOOLS/fna-vita/vita_sdl_overrides.c" "$TOOLS/fna3d-vita/vita_gl_glue.c" "$TOOLS/fna3d-vita/vita_glsl_rewrite.c" \
	"$T/vita_aot_modules.c"; do
	"${CC[@]}" -o "$STAGE/launcher/$(basename "$src").obj" -c "$src"
done
rm -rf "$T"

python3 "$TOOLS/filter-aotprofile.py" "$REPO/assets/stardew-1.aotprofile" "$STAGE/game.aotprofile" "Stardew Valley" \
	"$(sed -n "s/^DEFAULT_GAME_AOT_CLASSES='\(.*\)'$/\1/p" "$TOOLS/aot-stardew.sh")"

bash "$HERE/pack-toolchain.sh" --licenses-only > /dev/null
cp -r "$V/licenses" "$STAGE/licenses"
cat >> "$STAGE/licenses/README.txt" <<EOF

The $HOST toolchain (this zip): mono/bin is Mono 6.14.1 (MIT) built for $HOST by vpk/$SCRIPT, with the same
patches; mono/lib are Mono's class libraries (MIT). launcher/main.c.obj and the tables are ours (the builder
repository's overlay/game/Tools/Vita). VitaSDK is not included: the builder downloads its official release.
EOF

rm -f "$OUT"
(cd "$STAGE" && python3 - "$OUT" <<'EOF'
import os, sys, zipfile
with zipfile.ZipFile(sys.argv[1], "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
	for root, dirs, files in os.walk("."):
		dirs.sort()
		for f in sorted(files):
			p = os.path.join(root, f)
			z.write(p, os.path.relpath(p, "."))
EOF
)
ls -la "$OUT"
sha256sum "$OUT"
